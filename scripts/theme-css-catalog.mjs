// Writes the CSS of the design system's tokens from src/theme.compiled.json
// (its defaults, as the web builds them in src/utils/appTheme.js):
//  - tokens.tailwind.generated.css: the catalog as a Tailwind `@theme inline`
//    block (design-system/styles.css imports it), with the aliases, the web's
//    `background` / `secondary` under their own names (BRAND_COLORS) and the
//    theme's breakpoint.
// The dashboard's `--ds-*` names are written at runtime by ThemeCssVariables; there is no static file of them
// (nothing imported it).
// `--check` only compares (a vitest test runs it too). Not in theme:verify or cf:prepare.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { complete } from '@orderingco/ordering-theme-engine/runtime'
import { toCss } from '@orderingco/ordering-theme-engine/css'
import { catalogEntries, keysFromTokens } from '../src/ui/src/design-system/tokens/catalog.mjs'
import { tailwindLines } from '../src/ui/src/design-system/tokens/tailwind.mjs'
import { MOBILE_WEB_MAX_WIDTH } from '../src/utils/themeBreakpoint.mjs'

// (paths, not URLs: a test under jsdom has jsdom's URL, which node's fs refuses)
const ROOT = join(import.meta.dirname, '..')
const DIR = join(ROOT, 'src/ui/src/design-system/tokens')
export const FILES = {
  tailwind: join(DIR, 'tokens.tailwind.generated.css')
}
const header = (note) => `/* GENERATED by scripts/theme-css-catalog.mjs from src/theme.compiled.json: pnpm theme:css-catalog.${note} */\n`

/** The catalog with the schema's defaults as its values, read from the engine's CSS view. */
export const defaultEntries = () => {
  const compiled = JSON.parse(readFileSync(join(ROOT, 'src/theme.compiled.json'), 'utf8'))
  const values = complete(compiled, null)
  const css = toCss(compiled, values)
  const read = (group, key) => ({
    color: () => css.tokens.color[key],
    radius: () => css.identity.radius[key],
    space: () => css.tokens.space[key],
    size: () => css.tokens.size[key],
    icon: () => css.tokens.icon[key],
    shadow: () => css.identity.shadow[key].css,
    border: () => css.identity.border[key],
    border_fixed: () => css.tokens.border[key],
    opacity: () => css.tokens.opacity[key],
    typography: () => ({ size: css.tokens.typography[key].size, line: String(css.tokens.typography[key].line), weight: String(css.tokens.typography[key].weight) }),
    font: () => css.fonts[key].family,
    focus_ring: () => css.identity.focus_ring[key]
  })[group]()
  return catalogEntries(keysFromTokens(values.tokens), read)
}

const runtime = ({ ot, value }) => `var(${ot}, ${value})`

// Tailwind's own theme (colors, radii, fonts, `p-4`'s spacing, breakpoints,
// easings…) is cleared with `--*: initial`: a utility that is not a token of
// the theme does not exist. The one breakpoint is the theme's cut between a
// phone and the rest (`platforms.mobile_web`, below MOBILE_WEB_MAX_WIDTH):
// `ui:max-mobile:` is the phone, `ui:mobile:` the rest.
export const buildTailwindCss = (entries = defaultEntries()) => `${header('')}@theme inline {\n${[
  '--*: initial;',
  `--breakpoint-mobile: ${MOBILE_WEB_MAX_WIDTH}px;`,
  ...[...tailwindLines(entries)].map(([name, entry]) => `${name}: ${runtime(entry)};`)
].map((line) => `  ${line}`).join('\n')}\n}\n`

if (process.argv[1] === join(import.meta.dirname, 'theme-css-catalog.mjs')) {
  const built = { tailwind: buildTailwindCss() }
  if (process.argv.includes('--check')) {
    const stale = Object.keys(FILES).filter((name) => readFileSync(FILES[name], 'utf8') !== built[name])
    if (stale.length) {
      console.error(`${stale.map((name) => FILES[name]).join(', ')} out of date: run pnpm theme:css-catalog`)
      process.exit(1)
    }
    console.log('theme css catalog is up to date')
  } else {
    for (const name of Object.keys(FILES)) {
      writeFileSync(FILES[name], built[name])
      console.log(`wrote ${FILES[name]}`)
    }
  }
}
